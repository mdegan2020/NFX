function file = glasExample()
    %glasExample - Construct synthetic GLAS scanner metadata and imagery
    %   FILE = glasExample returns a generic NITF file with CSEXRB and the
    %   four typed sensor DESs. Values, IDs, pixels and covariance are
    %   synthetic and do not represent a calibrated sensor or a geolocation
    %   accuracy.
    %
    %   Add src and examples to the MATLAB path, then write the result:
    %       file = glasExample();
    %       file.write(fullfile(tempdir, 'nfx-glas-example.ntf'));
    %
    %   See also nfx.CSEXRB, nfx.CSATTB, nfx.CSEPHB, nfx.CSSFAB, nfx.CSCSDB

    imageID = '10000000-0000-4000-8000-000000000001';
    desIDs = { ...
        '20000000-0000-4000-8000-000000000001', ...
        '20000000-0000-4000-8000-000000000002', ...
        '20000000-0000-4000-8000-000000000003', ...
        '20000000-0000-4000-8000-000000000004'};

    exploitation = nfx.CSEXRB( ...
        image_uuid=imageID, assoc_des_uuid=desIDs, ...
        platform_id='DEMO', payload_id='DEMO', sensor_id='DEMO', ...
        sensor_type='S', day_first_line_image='20260915', ...
        time_first_line_image=43200, time_image_duration=1, ...
        num_lines=5, num_samples=7);

    attitude = nfx.CSATTB(uuid=desIDs{1}, aisdlvl=1, qual_flag_att=1, ...
        interp_type_att=1, att_type=1, eci_ecf_att=1, dt_att=1, ...
        date_att='20260915', t0_att='120000.000000000', ...
        q1=[0 0], q2=[0 0], q3=[0 0], q4=[1 1]);

    ephemeris = nfx.CSEPHB(uuid=desIDs{2}, aisdlvl=1, qual_flag_eph=1, ...
        interp_type_eph=1, ephem_flag=1, eci_ecf_ephem=1, dt_ephem=1, ...
        date_ephem='20260915', t0_ephem='120000.000000000', ...
        ephem_x=[7000000 7000000], ephem_y=[0 7000], ephem_z=[0 0]);

    alignment = nfx.CSSFAB(uuid=desIDs{3}, aisdlvl=1, sensor_type='S', ...
        band_wavelength=0.55, fl_interp=0, foc_length_date='20260915', ...
        foc_length_time=43200, foc_length=0.5, ...
        ppoff_x=0, ppoff_y=0, ppoff_z=0, ...
        angoff_x=0, angoff_y=0, angoff_z=0, ...
        smpl_num_first=0, delta_smpl_pairs=6, ...
        start_falign_x=-0.001, start_falign_y=0, ...
        end_falign_x=0.001, end_falign_y=0);

    group = nfx.SensorErrorGroup(corr_ref_date='20260915', ...
        corr_ref_time='120000.000000000', adj_parm_id=1:6, ...
        errcov_c1=diag([1 1 1 1e-6 1e-6 1e-6]));
    core = nfx.SensorErrorCore( ...
        ref_frame_position=1, ref_frame_attitude=2, groups=group);
    covariance = nfx.CSCSDB(uuid=desIDs{4}, aisdlvl=1, ...
        cov_version_date='20260915', cores=core);

    header = nfx.ImageHeader(iid1='GLAS_DEMO', idatim='20260915120000', ...
        isclas='U', irep='MONO', icat='VIS', ...
        nppbh=4, nppbv=3, isubcat=550);
    image = nfx.ImageSegment(reshape(uint16(1:35), 5, 7), ...
        header=header) + exploitation;
    file = nfx.File(header=nfx.FileHeader( ...
        ostaid='NFXDEMO', fdt='20260915120000', ...
        fsclas='U', ftitle='Synthetic GLAS demonstration')) ...
        + image + attitude + ephemeris + alignment + covariance;
end
