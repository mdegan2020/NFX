    blank = repmat(' ', 1, 166);
    file = ['NITF02.1003BF01ORIGIN    20260917000000' ...
        repmat(' ', 1, 80) 'U' blank '00000000000' char([1 2 3]) ...
        repmat(' ', 1, 42) '0000000008440004040010004390000000001' ...
        '0000000000000000000000000'];
    image = ['IMIMAGE     20260917000000' repmat(' ', 1, 97) ...
        'U' blank '0' repmat(' ', 1, 42) ...
        '0000000100000001INTMONO    VIS     08R 0NC1M       N   0' ...
        '0B00010001000100010800100000000000001.0 0000000000'];
    assert(numel(file) == 404 && numel(image) == 439);
    bytes = [uint8(file) uint8(image) uint8(197)];
end
